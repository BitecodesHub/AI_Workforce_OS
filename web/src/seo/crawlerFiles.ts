// @find: llms txt generator, llmstxt.org
/**
 * llms.txt for the site at `site`, in the llmstxt.org format: the H1, a one-sentence summary, then
 * free text (a paragraph and the key facts as a list, introduced by a sentence because headings
 * are not allowed there), then H2 sections that hold only lists of [name](url) links.
 */
export function llmsTxt(site: string): string {
  return [
    `# ${SITE_NAME}`,
    '',
    `> ${PRODUCT_DEFINITION}`,
    '',
    overview(),
    '',
    'Key facts:',
    '',
    ...keyFacts().map((fact) => `- ${fact}`),
    '',
    '## Pages',
    '',
    `- [Home page](${absoluteUrl(PUBLIC_PAGES.home.path, site)}): What the AI assistants do, how it works in three steps, example assistants, two demos, safety and common questions.`,
    `- [Security and technical details](${absoluteUrl(PUBLIC_PAGES.trust.path, site)}): For IT and security teams: the approval gate, provider failover, the tamper-evident audit chain, cited answers, the permissions of every role, what runs and the stated limits.`,
    '',
    '## Get started',
    '',
    `- [Create your workspace](${absoluteUrl('/create-workspace', site)}): The person who creates it becomes the owner and can invite everyone else.`,
    `- [Sign in](${absoluteUrl(PUBLIC_PAGES['sign-in'].path, site)}): For people who already have a workspace account.`,
    '',
    '## Optional',
    '',
    `- [Full text of the public pages](${absoluteUrl('/llms-full.txt', site)}): Every section, example and question of both pages in plain text.`,
    '',
  ].join('\n')
}

/** The home page's sections as Markdown, from the data its components render. */
function homeSections(): string[] {
  /** The built-in roles that hold every one of the codes, as "a, b and c". */
  const rolesHolding = (codes: readonly string[]) => listOf(ROLE_ORDER.filter((role) => holdsAll(role, codes)).map((role) => ROLE_LABEL[role]))
  return [
    '### Up and running in three steps',
    '',
    ...STEPS.map((step, index) => `${index + 1}. ${step.title}: ${step.body}`),
    '',
    'Example requests, and what happens to each:',
    '',
    ...REQUESTS.map((request) => {
      const agent = AGENTS.find((item) => item.id === request.agent)
      return `- "${request.text}": ${agent?.name ?? 'An assistant'} picks this up. ${request.alone} ${request.waits}`
    }),
    '',
    '### Example assistants for the work your team repeats',
    '',
    ...AGENTS.flatMap((agent) => [
      `- ${agent.name} (${agent.title.toLowerCase()}): ${agent.detail}`,
      ...AGENT_GRANTS[agent.id].map((grant) => `  - ${TOOL_LABEL[grant.server]}: ${grant.sentence}`),
    ]),
    '',
    'These are the example assistants of the demo workspace, whose tools use practice data.',
    '',
    '### Built so you stay in charge',
    '',
    ...PROMISES.map((promise) => `- ${promise.title}: ${promise.body}`),
    '',
    `Who can do what, in the ${countWord(BUILT_IN_ROLE_COUNT)} built-in roles every workspace starts with (owners and admins can create roles of their own):`,
    '',
    ...WHO_CAN.map((row) => `- ${row.label}: ${rolesHolding(row.codes)}`),
    '',
    '### What people ask before they start',
    '',
    ...FAQ_ITEMS.flatMap((item) => [`#### ${item.q}`, '', item.a, '']),
  ]
}

/** The technical page's sections as Markdown, from the data its components render. */
function trustSections(): string[] {
  return [
    ...TRUST_LEAD.flatMap((paragraph) => [paragraph, '']),
    '### Permissions of each role',
    '',
    ...ROLE_ORDER.map((role) => `- ${ROLE_LABEL[role]}: ${ROLE_SUMMARY[role]}`),
    '',
    '### What is actually running',
    '',
    `- ${SERVICE_COUNT} independent services.`,
    `- ${PROVIDERS.length} model providers (${listOf([...PROVIDERS])}), plus the offline sandbox model.`,
    `- ${CONNECTOR_COUNT} connectors (${listOf(connectorNames())}). All of them connect live once an administrator adds a token or signs in with the provider, and use practice data until then.`,
    `- ${PERMISSION_CODE_COUNT} permission codes, composed into roles.`,
    `- ${BUILT_IN_ROLE_COUNT} built-in roles, plus any roles a workspace composes.`,
    '',
    '### What it does not do',
    '',
    ...LIMITS.map((limit, index) => `${index + 1}. ${limit}`),
    '',
  ]
}

