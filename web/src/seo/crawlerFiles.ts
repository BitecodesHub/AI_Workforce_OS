/** Paths no crawler needs: the API and the deploy status file Caddy serves. */
export const DISALLOWED_PATHS: readonly string[] = ['/api/', '/deploy-status.json']

/** The canonical paths listed in the sitemap: the pages worth indexing. */
export const SITEMAP_PATHS: readonly string[] = [PUBLIC_PAGES.home.path, PUBLIC_PAGES.trust.path]

// @find: robots txt generator
/** robots.txt for the site at `site`. */
export function robotsTxt(site: string): string {
  const rules = ['Allow: /', ...DISALLOWED_PATHS.map((path) => `Disallow: ${path}`)]
  return [
    '# @find: robots.txt, crawler rules, search engines, AI crawlers, GPTBot, ClaudeBot, PerplexityBot, Google-Extended, CCBot, Bingbot, sitemap location',
    '# @what: Lets every crawler read the public site, keeps crawlers out of the API, and says where the sitemap is.',
    '# @flow: Generated by web/src/seo/crawlerFiles.ts (crawlerFiles.test.ts keeps web/public/robots.txt equal); served by nginx',
    '#',
    '# The signed-in app is not blocked here on purpose: a blocked page can never show a crawler its',
    '# noindex, so those screens answer with X-Robots-Tag: noindex instead.',
    '',
    'User-agent: *',
    ...rules,
    '',
    '# Search engines, AI answer engines and AI crawlers, named so the welcome is explicit. A named',
    '# group replaces the * group for that crawler, so it repeats the same rules.',
    ...NAMED_CRAWLERS.map((agent) => `User-agent: ${agent}`),
    ...rules,
    '',
    `Sitemap: ${absoluteUrl('/sitemap.xml', site)}`,
    '',
  ].join('\n')
}

/** The latest calendar date anywhere on Earth at `now` (UTC+14), as YYYY-MM-DD: a later date has not begun anywhere yet. */
function latestDateAt(now: Date): string {
  return new Date(now.getTime() + 14 * 60 * 60 * 1000).toISOString().slice(0, 10)
}

// @find: valid lastmod date, iso date check, future date, impossible date
/**
 * True for a real calendar date written YYYY-MM-DD, the form a sitemap's lastmod takes, that is not
 * in the future at `now` (the build). The value must survive a round trip through Date, so a day
 * that does not exist, such as 2026-02-30, which Date.parse would roll over into March, is
 * refused. A date counts as begun once it has begun in any time zone, so a content date written
 * where the day starts early (Australia, say) is not refused as tomorrow's.
 */
export function isIsoDate(value: string | undefined | null, now: Date = new Date()): value is string {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false
  const parsed = new Date(`${value}T00:00:00Z`)
  if (Number.isNaN(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== value) return false
  return value <= latestDateAt(now)
}

// @find: sitemap xml generator, lastmod
/** sitemap.xml for the site at `site`; `lastmod`, a YYYY-MM-DD content date, is added to each address only when it is a real date that is not later than `now`. */
export function sitemapXml(site: string, lastmod?: string | null, now: Date = new Date()): string {
  const dated = isIsoDate(lastmod, now) ? lastmod : null
  const urls = SITEMAP_PATHS.map((path) =>
    [
      '  <url>',
      `    <loc>${absoluteUrl(path, site)}</loc>`,
      ...(dated ? [`    <lastmod>${dated}</lastmod>`] : []),
      '  </url>',
    ].join('\n'),
  )
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!--',
    '  @find: sitemap.xml, sitemap, canonical addresses, pages to index',
    '  @what: Lists the public pages worth indexing by their canonical addresses.',
    '  @flow: Generated by web/src/seo/crawlerFiles.ts (crawlerFiles.test.ts keeps web/public/sitemap.xml equal); named by robots.txt; served by nginx',
    '-->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls,
    '</urlset>',
    '',
  ].join('\n')
}

/** Small counts as words, the way the pages write them in a sentence ("five roles"). */
const NUMBER_WORDS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten']

// @find: number in words, five roles, seven providers
/** A count as a word up to ten, or as digits above it; `capital` starts the word with a capital letter. */
export function countWord(count: number, capital = false): string {
  const word = NUMBER_WORDS[count] ?? String(count)
  return capital ? word.charAt(0).toUpperCase() + word.slice(1) : word
}

